// Turns the Figma "01 Home · Mobile" geometry (app/home-figma/mobile-layouts.raw.json, in the
// desktop widgets' native units) into the phone-only layout data and override stylesheet.
// Run: node scripts/build-mobile-home.mjs
import fs from 'node:fs';
const root=new URL('../app/home-figma/',import.meta.url);
const raw=JSON.parse(fs.readFileSync(new URL('mobile-layouts.raw.json',root),'utf8'));
const B=1.152,px=n=>+(n).toFixed(2)+'px',sel=id=>`.vxm-home .vxm-fit [data-node-id="${id}"]`;
const css=['/* Generated by scripts/build-mobile-home.mjs from Figma "01 Home · Mobile". Phone only. Do not edit by hand. */'];
const data={};
for(const [widget,spec] of Object.entries(raw)){
 const scale={};
 for(const [id,n] of Object.entries(spec.nodes)){
  // Longhands only: the CSS minifier merges and reorders rules, so a shorthand like inset would override left/top.
  const rules=[`left:${px(n.x-B)}`,`top:${px(n.y-B)}`,`width:${px(n.w)}`,`height:${px(n.h)}`,'right:auto','bottom:auto','translate:none','max-width:none'];
  if(n.align)rules.push(`text-align:${n.align.toLowerCase()}`);
  if(n.trunc)rules.push('white-space:nowrap','overflow:hidden','text-overflow:ellipsis');
  if(n.fs)rules.push(`font-size:${px(n.fs)} !important`);
  if(n.kids){rules[0]=`left:${px(-B)}`;rules[1]=`top:${px(-B)}`;rules[2]=`width:${px(n.w+2*B)}`;}
  css.push(`${sel(id)}{${rules.join(';')}}`);
  if(n.kids)for(const [kid,k] of Object.entries(n.kids))css.push(`${sel(kid)}{left:${px(k.x)};top:${px(k.y)};width:${px(k.w)};height:${px(k.h)};right:auto;bottom:auto;translate:none;max-width:none}`);
  if(n.ow&&Math.abs(n.w-n.ow)>0.5)scale[id]=+(n.w/n.ow).toFixed(4);
 }
 if(spec.cells)css.push(`.vxm-home .vxm-fit[data-fit="${widget}"] .vxm-cal-cells{left:${px(spec.cells.x-B)};top:${px(spec.cells.y-B)};width:${px(spec.cells.w)};height:${px(spec.cells.h)}}`);
 data[widget]={size:spec.size,hidden:spec.hidden,scale};
}
fs.writeFileSync(new URL('mobile-generated.css',root),css.join('\n')+'\n');
fs.writeFileSync(new URL('mobile-layouts.json',root),JSON.stringify(data)+'\n');
console.log('mobile layouts:',Object.keys(data).length,'widgets,',css.length-1,'rules');
